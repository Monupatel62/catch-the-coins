/**
 * generate-redirects.mjs
 * ----------------------
 * Auto-generates public/_redirects so every static page has ONE public URL.
 *
 * Why: the canonical tags and sitemap use "/page.html", but the host also serves
 * the extensionless "/page" with HTTP 200. Google then sees duplicates
 * ("Alternative page with proper canonical tag", "Discovered - currently not indexed").
 * A forced 301 from "/page" to "/page.html" removes the duplicate.
 *
 * Run manually:  npm run redirects
 * Runs on build: via the "prebuild" script.
 */
import { writeFileSync, readdirSync } from 'fs';
import { resolve, dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PUBLIC_DIR = resolve(__dirname, '../public');
const OUT_PATH = join(PUBLIC_DIR, '_redirects');

// Pages that must not be redirected.
const EXCLUDE = new Set(['404.html', 'index.html']);

function isVerificationFile(name) {
  return /^google[0-9a-f]+\.html$/i.test(name);
}

function htmlFilesIn(dir, urlPrefix) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.html'))
    .map((e) => e.name)
    .filter((name) => !EXCLUDE.has(name) && !isVerificationFile(name))
    .sort()
    .map((name) => `${urlPrefix}${name}`);
}

const pages = [...htmlFilesIn(PUBLIC_DIR, '/'), ...htmlFilesIn(join(PUBLIC_DIR, 'blog'), '/blog/')];

const lines = [
  '# AUTO-GENERATED by scripts/generate-redirects.mjs — do not edit by hand.',
  '# Extensionless URL -> canonical .html URL (forced, because a file exists at the path).',
  ...pages.map((p) => `${p.replace(/\.html$/, '')}  ${p}  301!`),
  '',
];

writeFileSync(OUT_PATH, lines.join('\n'), 'utf8');
console.log(`Wrote ${pages.length} redirects to public/_redirects`);
